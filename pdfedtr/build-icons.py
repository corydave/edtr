#!/usr/bin/env python3
"""
build-icons.py - regenerate PDFEDTR's icons and its install manifest.

It writes:
  - the icon block at the top of index.html: the tab icon and the home-screen
    icon as data: URIs, so the offline build (pdf-offline.html) still has an
    icon when it is opened straight off a disk
  - manifest.webmanifest, icon-192.png, icon-512.png and icon-maskable-512.png
    beside index.html. Upload them with it: browsers only offer "Install" for
    a manifest that is a real file on the same site as the page. (Until 1.6
    the manifest was a data: URI too, which is why Chrome never offered its
    own Install for PDFEDTR while it did for the other apps.)

Why PNG and not just the SVG: Chrome will not use an SVG icon for PWA
install. It reads the manifest fine and then silently falls back to a
generated letter tile, which is what "the icon doesn't stick" looks like.
PNG at 192 and 512 is what Chrome actually wants. The SVG is still used for
the browser tab, where it is supported and stays crisp at any size.

Run this after changing icon.svg, then re-run build-offline.py.
"""

import base64
import io
import pathlib
import re

import cairosvg

HERE = pathlib.Path(__file__).resolve().parent     # the folder this script is in
SRC = HERE / 'index.html'
ICON = HERE / 'icon.svg'

APP_NAME = 'PDFEDTR'
THEME = '#8a1c5c'   # PDFEDTR plum


def png_bytes(svg_bytes, size):
    buf = io.BytesIO()
    cairosvg.svg2png(bytestring=svg_bytes, write_to=buf,
                     output_width=size, output_height=size)
    return buf.getvalue()


def png_data_uri(svg_bytes, size):
    return 'data:image/png;base64,' + base64.b64encode(png_bytes(svg_bytes, size)).decode()


def main():
    svg = ICON.read_bytes()

    # Standard icons keep the rounded tile (transparent corners).
    icon192 = png_data_uri(svg, 192)
    icon512 = png_data_uri(svg, 512)

    # The maskable icon is squared off (rx=0) so it bleeds edge to edge.
    # Android crops maskable icons to whatever shape the launcher uses -
    # a circle, a squircle - so transparent corners would show as notches.
    # The page-and-pencil art sits well inside the centre 80% safe zone,
    # so nothing important gets cropped.
    svg_full_bleed = svg.replace(b'rx="7"', b'rx="0"')
    maskable512 = png_data_uri(svg_full_bleed, 512)

    # The same three icons as files, for the manifest.
    (HERE / 'icon-192.png').write_bytes(png_bytes(svg, 192))
    (HERE / 'icon-512.png').write_bytes(png_bytes(svg, 512))
    (HERE / 'icon-maskable-512.png').write_bytes(png_bytes(svg_full_bleed, 512))

    svg_uri = 'data:image/svg+xml;base64,' + base64.b64encode(svg).decode()

    # The install manifest, as a file beside index.html.
    manifest = f'''{{
  "name": "{APP_NAME}",
  "short_name": "{APP_NAME}",
  "description": "Browser-only PDF editor. No uploads, no network.",
  "id": "./",
  "start_url": "./",
  "scope": "./",
  "display": "standalone",
  "background_color": "#ffffff",
  "theme_color": "{THEME}",
  "icons": [
    {{ "src": "icon-192.png", "sizes": "192x192", "type": "image/png", "purpose": "any" }},
    {{ "src": "icon-512.png", "sizes": "512x512", "type": "image/png", "purpose": "any" }},
    {{ "src": "icon-maskable-512.png", "sizes": "512x512", "type": "image/png", "purpose": "maskable" }}
  ]
}}
'''
    (HERE / 'manifest.webmanifest').write_text(manifest, encoding='utf-8')

    block = f'''  <!-- APP-ICON-BLOCK-START - generated by build-icons.py, do not hand-edit.
       The icons here are data: URIs, so the offline build still has them
       when it is opened straight off a disk. -->

  <!-- Tab icon. SVG first for crispness; the PNG is the fallback for
       browsers that will not take an SVG favicon. -->
  <link rel="icon" type="image/svg+xml" href="{svg_uri}" />
  <link rel="icon" type="image/png" sizes="192x192" href="{icon192}" />
  <link rel="apple-touch-icon" href="{icon192}" />

  <!-- Makes the page installable with a real name and icon. The manifest
       is a real file (built beside this page by build-icons.py): browsers
       only offer Install for one on the same site as the page. Its icons
       are PNG because Chrome will not install with an SVG icon. Opened
       straight from disk (file://), browsers ignore the manifest. -->
  <link rel="manifest" href="manifest.webmanifest" />
  <meta name="theme-color" content="{THEME}" />
  <meta name="mobile-web-app-capable" content="yes" />
  <meta name="apple-mobile-web-app-capable" content="yes" />
  <meta name="apple-mobile-web-app-title" content="{APP_NAME}" />
  <!-- APP-ICON-BLOCK-END -->
'''

    html = SRC.read_text(encoding='utf-8')
    pattern = re.compile(
        r'  <!-- APP-ICON-BLOCK-START.*?<!-- APP-ICON-BLOCK-END -->\n',
        re.DOTALL,
    )
    html, n = pattern.subn(lambda m: block, html)
    assert n == 1, f'expected 1 app-icon block in index.html, replaced {n}'
    SRC.write_text(html, encoding='utf-8')

    size = SRC.stat().st_size
    print(f'Patched {SRC} - now {size:,} bytes ({size/1024:.0f} KB)')
    print(f'  icon 192 png : {len(icon192):,} chars')
    print(f'  icon 512 png : {len(icon512):,} chars')
    print(f'  maskable 512 : {len(maskable512):,} chars')


if __name__ == '__main__':
    main()
